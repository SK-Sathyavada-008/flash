"""Action 4: create_grocery_list - creates a formatted grocery checklist and saves to disk."""

from datetime import datetime
from typing import Any
from app.actions.base import BaseAction
from app.models import ActionResponse
from app.security import resolve_safe_path
from app.logging_config import get_logger

logger = get_logger("flash.action.create_grocery_list")


class CreateGroceryListAction(BaseAction):
    name = "create_grocery_list"
    description = "Generates a formatted grocery checklist markdown document and saves it inside the Flash workspace."
    requires_confirmation = False
    parameters_schema = {
        "items": {
            "type": "array",
            "required": True,
            "description": "List of grocery items (strings or categorized dictionaries).",
        },
        "title": {
            "type": "string",
            "required": False,
            "description": "Custom title for the checklist (default: 'Flash Grocery Checklist').",
            "default": "Flash Grocery Checklist",
        },
        "filename": {
            "type": "string",
            "required": False,
            "description": "Relative filename to save into (default: 'lists/grocery_list_YYYYMMDD_HHMM.md').",
        },
    }

    def run(self, parameters: dict[str, Any], confirmed: bool = False) -> ActionResponse:
        raw_items = parameters.get("items")
        if not raw_items or not isinstance(raw_items, list):
            return ActionResponse(
                success=False,
                action=self.name,
                message="Parameter 'items' is required and must be a non-empty list.",
                error="MISSING_PARAMETER",
            )

        title = str(parameters.get("title") or "Flash Grocery Checklist").strip()
        timestamp_str = datetime.now().strftime("%Y-%m-%d %H:%M")
        file_timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")

        default_filename = f"lists/grocery_list_{file_timestamp}.md"
        target_filename = str(parameters.get("filename") or default_filename).strip()

        is_safe, resolved_path, error_msg = resolve_safe_path(
            target_filename,
            must_exist=False,
            create_parent=True,
        )

        if not is_safe or resolved_path is None:
            return ActionResponse(
                success=False,
                action=self.name,
                message=f"Access denied: {error_msg}",
                error="PATH_ACCESS_DENIED",
            )

        # Build Markdown content
        lines = [
            f"# 🛒 {title}",
            f"*Generated by Flash on {timestamp_str}*",
            "",
            "---",
            "",
        ]

        item_count = 0
        categories_found: set[str] = set()

        import re

        # Normalize and split comma-separated or conjunction-separated items
        flat_items: list[str] = []
        for item in raw_items:
            if isinstance(item, dict):
                cat = item.get("category", "General Items")
                categories_found.add(cat)
                lines.append(f"### {cat}")
                for sub in item.get("items", []):
                    parts = re.split(r",|;|\n|\sand\s", str(sub), flags=re.IGNORECASE)
                    for p in parts:
                        cleaned = re.sub(r"^(?:and|buy|get|a|an)\s+", "", p.strip(), flags=re.IGNORECASE).strip()
                        cleaned = re.sub(r"^[-*•]\s*", "", cleaned).strip()
                        if cleaned:
                            lines.append(f"- [ ] {cleaned}")
                            item_count += 1
                lines.append("")
            else:
                parts = re.split(r",|;|\n|\sand\s", str(item), flags=re.IGNORECASE)
                for p in parts:
                    cleaned = re.sub(r"^(?:and|buy|get|a|an)\s+", "", p.strip(), flags=re.IGNORECASE).strip()
                    cleaned = re.sub(r"^[-*•]\s*", "", cleaned).strip()
                    if cleaned:
                        lines.append(f"- [ ] {cleaned}")
                        item_count += 1

        lines.append("")

        lines.extend([
            "---",
            f"**Total items:** {item_count}",
            "",
            "> 🦥 *\"Take your time picking the freshest ingredients!\"* — Flash",
        ])

        content = "\n".join(lines) + "\n"

        try:
            resolved_path.write_text(content, encoding="utf-8")
            logger.info("Saved grocery list to %s (%d items)", resolved_path, item_count)

            return ActionResponse(
                success=True,
                action=self.name,
                message=f"Grocery list '{resolved_path.name}' created with {item_count} item(s).",
                output_path=str(resolved_path),
                data={
                    "title": title,
                    "item_count": item_count,
                    "categories": sorted(categories_found) if categories_found else ["General"],
                    "path": str(resolved_path),
                },
            )
        except Exception as e:
            logger.error("Failed to write grocery list: %s", e, exc_info=True)
            return ActionResponse(
                success=False,
                action=self.name,
                message=f"Failed to save grocery list: {e}",
                output_path=str(resolved_path),
                error=str(e),
            )
