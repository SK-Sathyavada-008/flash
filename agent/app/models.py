class PairingCodeResponse(BaseModel):
    """Pairing code generated on the host agent."""

    code: str = Field(..., description="6-digit formatted pairing code (e.g. '123-456').")
    expires_in_seconds: int = Field(..., description="Remaining lifetime of code in seconds.")
    expires_at: float = Field(..., description="Unix timestamp when code expires.")


class PairRequest(BaseModel):
    """Phone companion pairing request."""

    code: str = Field(..., description="6-digit code displayed on the desktop agent.")
    device_name: str = Field(default="Redmi Android", description="Human-readable device nickname.")


class PairResponse(BaseModel):
    """Successful pairing response containing revocable bearer token."""

    token: str = Field(..., description="Cryptographically secure 256-bit bearer token.")
    device_name: str = Field(..., description="Registered device name.")
    status: str = Field(default="authenticated", description="Authentication status.")


class RevokeTokenRequest(BaseModel):
    """Request to revoke an authorized bearer token."""

    token: str = Field(..., description="Token to be revoked.")


class RevokeTokenResponse(BaseModel):
    """Outcome of token revocation."""

    success: bool = Field(..., description="Whether the token was found and revoked.")
    message: str = Field(..., description="Status summary.")


class WebSocketInboundMessage(BaseModel):
    """Validated inbound message from phone companion over WebSocket."""

    type: str = Field(..., description="Message type: 'ping', 'execute_task', 'stop', 'resume', 'get_status'.")
    prompt: Optional[str] = Field(default=None, description="Prompt text when type is 'execute_task'.")
    confirmed: Optional[bool] = Field(default=False, description="Confirmation flag for destructive tasks.")
    timestamp: Optional[float] = Field(default=None, description="Client timestamp for latency calculation.")


class WebSocketOutboundMessage(BaseModel):
    """Structured outbound message sent from agent to phone companion."""

    type: str = Field(..., description="Event type, e.g. 'pong', 'task_started', 'task_step_progress', 'task_finished'.")
    timestamp: float = Field(default_factory=time.time, description="Server Unix timestamp.")
    data: dict[str, Any] = Field(default_factory=dict, description="Arbitrary payload attributes.")


