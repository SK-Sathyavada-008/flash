"""Pydantic request and response models for Flash Agent."""

import time
from typing import Any, Optional
from pydantic import BaseModel, Field


class ActionRequest(BaseModel):
    """Payload for invoking an action on the agent."""

    action: str = Field(..., description="The unique name of the registered action to invoke.")
    parameters: dict[str, Any] = Field(
        default_factory=dict, description="Arbitrary parameters passed to the action handler."
    )
    confirmed: bool = Field(
        default=False,
        description="Explicit user confirmation for actions tagged as requiring confirmation.",
    )


class ActionResponse(BaseModel):
    """Structured response returned for every action invocation."""

    success: bool = Field(..., description="Whether the action succeeded.")
    action: str = Field(..., description="The action name that was executed.")
    message: str = Field(..., description="Human-readable explanation of the result.")
    output_path: Optional[str] = Field(
        default=None, description="Path to generated file or resource, if applicable."
    )
    data: Optional[dict[str, Any]] = Field(
        default=None, description="Structured output data returned by the action."
    )
    error: Optional[str] = Field(
        default=None, description="Error code or details if the action failed."
    )
    execution_time_ms: float = Field(
        default=0.0, description="Execution duration in milliseconds."
    )


class ActionInfo(BaseModel):
    """Metadata describing an available registered action."""

    name: str = Field(..., description="Action identifier.")
    description: str = Field(..., description="Summary of action capability.")
    requires_confirmation: bool = Field(
        default=False, description="Whether confirmation is mandated before execution."
    )
    parameters_schema: dict[str, Any] = Field(
        default_factory=dict, description="Schema definition of accepted parameters."
    )


class AgentStatusResponse(BaseModel):
    """System and operational status report."""

    status: str = Field(..., description="Current operational state: 'ready', 'stopped', 'busy', etc.")
    character: str = Field(default="Flash", description="Active agent character persona.")
    version: str = Field(..., description="Software version.")
    emergency_stop_active: bool = Field(..., description="Whether the global emergency stop circuit is active.")
    workspace_dir: str = Field(..., description="Resolved path of approved workspace.")
    available_actions: list[str] = Field(default_factory=list, description="List of registered action names.")
    action_details: list[ActionInfo] = Field(default_factory=list, description="Detailed schema for each action.")
    system_info: dict[str, Any] = Field(default_factory=dict, description="Host OS and runtime platform details.")


class HealthResponse(BaseModel):
    """Health check endpoint response model."""

    status: str = Field(default="ok", description="Service health indicator.")
    app: str = Field(..., description="Service application name.")
    version: str = Field(..., description="Service application version.")
    timestamp: str = Field(..., description="ISO 8601 current timestamp.")


# =====================================================================
# Milestone 2: AI Integration & Task Orchestration Models
# =====================================================================

class OllamaStatusResponse(BaseModel):
    """Status report for local Ollama installation and Gemma model."""

    is_installed: bool = Field(..., description="Whether Ollama CLI/daemon is installed.")
    is_running: bool = Field(..., description="Whether Ollama HTTP API is reachable.")
    configured_model: str = Field(..., description="Model name configured in settings.")
    is_model_available: bool = Field(..., description="Whether the configured model is installed locally.")
    available_models: list[str] = Field(default_factory=list, description="List of all locally available Ollama models.")
    setup_instructions: Optional[str] = Field(
        default=None, description="Actionable command/guidance if Ollama or model is missing."
    )


class ActionPlanItem(BaseModel):
    """A single validated action planned by Gemma."""

    action_name: str = Field(..., description="Name of the registered action tool.")
    parameters: dict[str, Any] = Field(default_factory=dict, description="Validated parameters for the action.")
    requires_confirmation: bool = Field(
        default=False, description="Whether this specific action requires user confirmation."
    )
    explanation: str = Field(
        default="Executing action step",
        description="Brief human-readable description of what this step does.",
    )


class InterpretationPlan(BaseModel):
    """Structured plan generated by Gemma from natural-language instructions."""

    intent: str = Field(..., description="High-level interpretation of user's intent.")
    user_facing_explanation: str = Field(
        default="Processing your request slowly and steadily...",
        description="Short explanation (< 30 words) for speech bubble or caption.",
    )
    actions: list[ActionPlanItem] = Field(
        default_factory=list, description="Sequence of validated actions to achieve the intent."
    )
    needs_confirmation: bool = Field(
        default=False, description="True if one or more planned actions require explicit confirmation."
    )


class UserTaskRequest(BaseModel):
    """Incoming natural-language request from user."""

    prompt: str = Field(..., description="Natural-language instruction, e.g. 'Make a grocery list with milk'.")
    confirmed: bool = Field(
        default=False, description="Explicit user confirmation for actions requiring permission."
    )


class TaskStepResult(BaseModel):
    """Execution outcome of a single step within an orchestrated task."""

    step_index: int = Field(..., description="1-based index of this step in the plan.")
    action_name: str = Field(..., description="Executed action name.")
    explanation: str = Field(..., description="Step explanation.")
    success: bool = Field(..., description="Whether this step succeeded.")
    result: ActionResponse = Field(..., description="Structured output returned by the action.")


class TaskExecutionResponse(BaseModel):
    """Final result of an orchestrated natural-language task."""

    task_id: str = Field(..., description="Unique task identifier.")
    prompt: str = Field(..., description="Original user prompt.")
    intent: str = Field(..., description="Interpreted user intent.")
    status: str = Field(..., description="'completed', 'failed', 'awaiting_confirmation', or 'halted'.")
    success: bool = Field(..., description="Whether the entire task completed successfully.")
    explanation: str = Field(..., description="User-facing summary message.")
    steps: list[TaskStepResult] = Field(default_factory=list, description="Individual results for each executed step.")
    execution_time_ms: float = Field(default=0.0, description="Total execution time in milliseconds.")
    error: Optional[str] = Field(default=None, description="Error code or description if failed.")


