"""Configuration management for Flash Windows Desktop Agent.
Uses Pydantic BaseSettings to read environment variables with secure defaults.
"""

from pathlib import Path
from pydantic_settings import BaseSettings, SettingsConfigDict
from pydantic import Field


class Settings(BaseSettings):
    """Application settings for Flash Agent."""

    model_config = SettingsConfigDict(
        env_prefix="FLASH_",
        env_file=".env",
        env_file_encoding="utf-8",
        extra="ignore",
    )

    # Core service binding (strictly localhost by default)
    host: str = Field(default="127.0.0.1", description="Bind host address. Strictly localhost.")
    port: int = Field(default=8765, description="Port for the FastAPI service.")
    debug: bool = Field(default=False, description="Debug mode flag.")

    # Application metadata
    app_name: str = Field(default="Flash Windows Desktop Agent", description="Agent service name.")
    app_version: str = Field(default="0.1.0", description="Agent software version.")
    character_name: str = Field(default="Flash", description="Character persona name.")

    # Logging
    log_level: str = Field(default="INFO", description="Logging level (DEBUG, INFO, WARNING, ERROR).")
    log_to_file: bool = Field(default=True, description="Whether to write logs to disk.")

    # Workspace & filesystem sandboxing
    # Defaults to %USERPROFILE%/Documents/Flash Workspace
    workspace_dir: Path = Field(
        default_factory=lambda: Path.home() / "Documents" / "Flash Workspace",
        description="Root approved workspace directory for all file operations.",
    )
    storage_base_dir: str = Field(
        default="",
        description="Optional override directory for Flash data and routines.",
    )

    # Security controls
    emergency_stop_enabled: bool = Field(default=True, description="Enables the global emergency stop circuit.")
    require_confirmation_for_destructive: bool = Field(
        default=True, description="Requires explicit confirmation flags for destructive operations."
    )
    allowed_url_schemes: tuple[str, ...] = ("http", "https")
    blocked_url_hosts: tuple[str, ...] = ("localhost", "127.0.0.1", "0.0.0.0", "::1")
    allow_internal_urls: bool = Field(default=False, description="Whether to allow opening localhost/loopback URLs.")

    # AI & Local Inference (Ollama + Gemma)
    ollama_base_url: str = Field(
        default="http://127.0.0.1:11434",
        description="Local Ollama daemon API URL.",
    )
    ollama_model: str = Field(
        default="gemma2:2b",
        description="Configured local Gemma model tag in Ollama.",
    )
    ollama_timeout_seconds: float = Field(
        default=35.0,
        description="Timeout in seconds for local model inference.",
    )
    ollama_temperature: float = Field(
        default=0.1,
        description="Sampling temperature for deterministic structured tool calling.",
    )
    ollama_num_predict: int = Field(
        default=180,
        description="Maximum tokens generated by Ollama per completion.",
    )
    fast_path_enabled: bool = Field(
        default=True,
        description="Whether to use instant rule-based parsing for recognized common commands.",
    )
    multi_step_error_policy: str = Field(
        default="stop_on_error",
        description="Policy for multi-step task execution on failure: 'stop_on_error' or 'continue_on_error'.",
    )

    # --- Milestone 6 Partner Integrations ---
    # Speech Provider (ElevenLabs / Local)
    speech_provider: str = Field(
        default="local",
        description="Speech synthesis provider: 'local' (offline/browser) or 'elevenlabs'.",
    )
    elevenlabs_api_key: str = Field(
        default="",
        description="Optional ElevenLabs API key for high-fidelity speech synthesis.",
    )
    elevenlabs_voice_id: str = Field(
        default="21m00Tcm4TlvDq8ikWAM",  # Rachel (default standard voice)
        description="ElevenLabs voice identifier.",
    )

    # Browser Provider (Stagehand / Browserbase / Local Playwright)
    browser_provider: str = Field(
        default="local",
        description="Browser execution provider: 'local' (local Playwright) or 'browserbase'.",
    )
    browserbase_api_key: str = Field(
        default="",
        description="Optional Browserbase API key for cloud browser execution.",
    )
    browserbase_project_id: str = Field(
        default="",
        description="Optional Browserbase Project ID.",
    )

    # Cloud Storage Provider (MongoDB Atlas / Local JSON)
    storage_provider: str = Field(
        default="local",
        description="Persistence backend for user routines/preferences: 'local' (JSON) or 'mongodb'.",
    )
    mongodb_uri: str = Field(
        default="",
        description="Optional MongoDB Atlas connection string (mongodb+srv://...).",
    )
    mongodb_database_name: str = Field(
        default="flash_desktop",
        description="MongoDB database name.",
    )

    # Telemetry & Error Tracking (Sentry)
    sentry_dsn: str = Field(
        default="",
        description="Optional Sentry DSN for error telemetry and agent tracing.",
    )
    sentry_environment: str = Field(
        default="development",
        description="Sentry deployment environment tag.",
    )
    sentry_traces_sample_rate: float = Field(
        default=1.0,
        description="Sentry performance tracing sample rate.",
    )

    # Cloud Coordination / Render
    render_external_url: str = Field(
        default="",
        description="Public URL for Render-hosted cloud coordination service or landing page.",
    )

    def ensure_directories(self) -> None:
        """Ensure necessary runtime directories exist."""
        self.workspace_dir.mkdir(parents=True, exist_ok=True)
        (self.workspace_dir / "lists").mkdir(parents=True, exist_ok=True)
        (self.workspace_dir / "spreadsheets").mkdir(parents=True, exist_ok=True)
        (self.workspace_dir / "documents").mkdir(parents=True, exist_ok=True)


def mask_sensitive_data(value: str) -> str:
    """Mask potentially sensitive tokens, keys, or passwords for logging."""
    if not value or len(value) <= 6:
        return "***"
    return value[:3] + "..." + value[-3:]


# Global settings singleton
settings = Settings()
